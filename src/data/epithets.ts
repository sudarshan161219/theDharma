/** Why a name was given. */
export type NameKind = 'deed' | 'form' | 'relation' | 'quality' | 'role' | 'place';

export const kindInfo: Record<NameKind, { label: string; about: string; example: string }> = {
  deed: { label: 'From a deed', about: 'A victory or an act from the stories.', example: 'Madhusudana, “slayer of Madhu”' },
  form: { label: 'From the form', about: 'How the deity looks, or what it holds.', example: 'Nilakantha, “the blue-throated”' },
  relation: { label: 'From a relation', about: 'Parent, spouse, child or devotee.', example: 'Parvati, “daughter of the mountain”' },
  quality: { label: 'From a quality', about: 'An inner nature or power.', example: 'Achyuta, “the one who never falls”' },
  role: { label: 'From a cosmic role', about: 'What the deity does for the world.', example: 'Vighneshvara, “lord of obstacles”' },
  place: { label: 'From a place', about: 'An abode or a shrine.', example: 'Vishvanatha, lord of Kashi' },
};

